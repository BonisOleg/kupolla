def seed_team_members(apps=None):
    """Сидить 7 членів команди KUPOLLA (сторінка «Про компанію», блок «Команда»)."""
    if apps is not None:
        TeamMember = apps.get_model('pages', 'TeamMember')
    else:
        from src.pages.models import TeamMember

    for item in TEAM_MEMBERS:
        TeamMember.objects.get_or_create(
            order=item['order'],
            defaults={
                'name': item['name'],
                'position': item['position'],
                'position_uk': item['position'],
            },
        )


def _with_uk_fields(data: dict) -> dict:
    payload = dict(data)
    for key, value in list(payload.items()):
        if not key.endswith('_uk') and isinstance(value, str) and value:
            uk_key = f'{key}_uk'
            if uk_key not in payload:
                payload[uk_key] = value
    return payload


