def seed_blog():
    from src.blog.models import Category, Post
    from src.core.seed_utils import assign_image_field

    categories = {}
    for item in BLOG_CATEGORIES:
        cat, _ = Category.objects.update_or_create(
            slug=item['slug'],
            defaults={'name': item['name'], 'name_uk': item['name']},
        )
        categories[item['slug']] = cat

    for item in BLOG_POSTS:
        post, created = Post.objects.update_or_create(
            slug=item['slug'],
            defaults={
                'title': item['title'],
                'title_uk': item['title'],
                'excerpt': item['excerpt'],
                'excerpt_uk': item['excerpt'],
                'body': item['body'],
                'body_uk': item['body'],
                'category': categories[item['category']],
                'is_published': True,
                'published_at': item['published_at'],
                'seo_title': item.get('seo_title', item['title'][:70]),
                'seo_description': item['excerpt'][:160],
            },
        )
        assign_image_field(post, 'cover_image', item['cover'], 'blog')
        post.save()
