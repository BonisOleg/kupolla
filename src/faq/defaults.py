def seed_faq(apps):
    FAQGroup = apps.get_model('faq', 'FAQGroup')
    FAQItem = apps.get_model('faq', 'FAQItem')

    for group_data in FAQ_GROUPS:
        items = group_data['items']
        group_name = group_data['name']
        group, _ = FAQGroup.objects.update_or_create(
            name=group_name,
            defaults={
                'name_uk': group_name,
                'order': group_data['order'],
            },
        )
        for order, (question, answer) in enumerate(items):
            FAQItem.objects.update_or_create(
                group=group,
                question=question,
                defaults={
                    'question_uk': question,
                    'answer': answer,
                    'answer_uk': answer,
                    'order': order,
                    'is_published': True,
                },
            )
